// Generates frontend/components/icons.js from the lucide package (run: npm run icons). Only the icons listed here ship.
import * as lucide from 'lucide';
import fs from 'node:fs';

const MAP = {
  home: 'House', history: 'History', calendar: 'CalendarDays', leave: 'CalendarCheck', flag: 'ClipboardCheck',
  briefcase: 'BriefcaseBusiness', clock: 'Clock', book: 'BookOpen', chart: 'ChartColumn', logout: 'LogOut',
  check: 'Check', close: 'X', users: 'UserCheck', inbox: 'Inbox', mic: 'Mic', stop: 'Square', sun: 'Sun',
  moon: 'Moon', search: 'Search', arrow: 'ArrowRight', back: 'ArrowLeft', cpu: 'Cpu', radio: 'Radio', gear: 'Cog',
  school: 'GraduationCap', eye: 'Eye', eyeOff: 'EyeOff', id: 'IdCard', lock: 'Lock', play: 'Play', bot: 'Bot',
  volume: 'Volume2', spark: 'Sparkles', phone: 'Phone', mail: 'Mail', mapPin: 'MapPin', globe: 'Globe',
};

const nodes = {};
for (const [name, lucideName] of Object.entries(MAP)) {
  if (!lucide[lucideName]) throw new Error(`lucide has no icon ${lucideName}`);
  nodes[name] = lucide[lucideName];
}

const out = `// Generated by scripts/build-icons.mjs from lucide (ISC licence). Do not edit by hand.
const SVG_NS = 'http://www.w3.org/2000/svg';
const NODES = ${JSON.stringify(nodes)};

/** Lucide icon as an inline SVG element (24px grid, stroke = currentColor, strokeWidth 2). */
export function icon(name, size = 24, strokeWidth = 2) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  const attrs = { viewBox: '0 0 24 24', width: size, height: size, fill: 'none', stroke: 'currentColor', 'stroke-width': strokeWidth, 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'aria-hidden': 'true', class: \`icon lucide-\${name}\` };
  for (const [k, v] of Object.entries(attrs)) svg.setAttribute(k, v);
  for (const [tag, a] of NODES[name] ?? []) {
    const child = document.createElementNS(SVG_NS, tag);
    for (const [k, v] of Object.entries(a)) child.setAttribute(k, v);
    svg.append(child);
  }
  return svg;
}
`;
fs.writeFileSync(new URL('../frontend/components/icons.js', import.meta.url), out);
console.log(`icons.js: ${Object.keys(nodes).length} lucide icons`);
